import { test, expect } from "@playwright/test";
import { randomBytes, randomUUID } from "node:crypto";
import { readEmailCode, registerSeller } from "./seller-account";

test("注册账号建单、退出重新登录找回订单，其他卖家不能访问", async ({ page, browser, baseURL }) => {
  test.setTimeout(90000);
  const email = `seller-${randomUUID()}@example.invalid`;
  const password = `A1!${randomBytes(4).toString("hex")}`;
  const product = `账号验收虚构商品 ${Date.now()}`;
  await page.goto("/orders/new");
  await expect(page.getByRole("heading", { name: "请先登录卖家账号" })).toBeVisible();
  await page.getByRole("link", { name: "注册卖家账号", exact: true }).click();
  await page.getByLabel("你的称呼", { exact: true }).fill("虚构账号卖家");
  await page.getByLabel("邮箱", { exact: true }).fill(email);
  await page.getByLabel("密码", { exact: true }).fill(password);
  await page.getByRole("button", { name: "获取验证码", exact: true }).click();
  await expect(page.getByText(/验证码已发送/)).toBeVisible();
  const code = await readEmailCode(email);
  await page.getByLabel("邮箱验证码", { exact: true }).fill(code);
  await page.getByLabel("确认密码", { exact: true }).fill("Different12!");
  await page.getByRole("button", { name: /验证邮箱并注册/ }).click();
  await expect(page.locator("form").getByRole("alert")).toHaveText("两次输入的密码不一致。");
  await page.getByLabel("确认密码", { exact: true }).fill(password);
  await page.setViewportSize({ width: 390, height: 844 });
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth + 1)).toBe(true);
  if (process.env.E2E_ARTIFACT_DIR) await page.screenshot({ path: `${process.env.E2E_ARTIFACT_DIR}/seller-register-mobile.png`, fullPage: true });
  const wrongCode = code === "000001" ? "000002" : "000001";
  await page.getByLabel("邮箱验证码", { exact: true }).fill(wrongCode);
  await page.getByRole("button", { name: /验证邮箱并注册/ }).click();
  await expect(page.locator("form").getByRole("alert")).toHaveText("验证码不正确或已过期，请检查邮箱或重新获取。");
  await page.getByLabel("邮箱验证码", { exact: true }).fill(code);
  await page.getByRole("button", { name: /验证邮箱并注册/ }).click();
  await expect(page).toHaveURL(/\/orders\/new$/);
  await page.getByLabel("商品明细信息", { exact: false }).fill("黑色硅胶桌面理线夹，参数待核实。");
  await page.getByLabel(/商品名字/).fill(product);
  await page.getByRole("button", { name: /保存资料，创建订单/ }).click();
  await expect(page.getByRole("heading", { name: /资料已保存/ })).toBeVisible();
  const privateUrl = await page.getByLabel("私有订单链接").inputValue();
  await page.getByRole("link", { name: /返回我的订单/ }).click();
  await expect(page.getByRole("link", { name: new RegExp(product) })).toBeVisible();
  if (process.env.E2E_ARTIFACT_DIR) await page.screenshot({ path: `${process.env.E2E_ARTIFACT_DIR}/seller-orders-mobile.png`, fullPage: true });
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth + 1)).toBe(true);
  await page.getByRole("button", { name: /退出卖家账号/ }).click();
  await expect(page).toHaveURL(/\/seller\/login$/);
  await page.goto("/orders/new");
  await expect(page.getByRole("heading", { name: "请先登录卖家账号" })).toBeVisible();
  // New browser context has no prior session or private link.
  const fresh = await browser.newContext({ baseURL });
  try {
    const restored = await fresh.newPage();
    await restored.goto("/seller/login");
    await restored.getByLabel("邮箱", { exact: true }).fill(email);
    await restored.getByLabel("密码", { exact: true }).fill("incorrect-password");
    await restored.getByRole("button", { name: /登录卖家账号/ }).click();
    await expect(restored.locator("form").getByRole("alert")).toHaveText("邮箱或密码不正确。");
    await restored.getByLabel("密码", { exact: true }).fill(password);
    await restored.getByRole("button", { name: /登录卖家账号/ }).click();
    await expect(restored).toHaveURL(/\/seller\/orders$/);
    await restored.getByRole("link", { name: new RegExp(product) }).click();
    await expect(restored.getByRole("heading", { level: 1 })).toContainText(product);
    expect(new URL(restored.url()).hash).toBe("");
    await restored.reload();
    await expect(restored.getByRole("heading", { level: 1 })).toContainText(product);
  } finally { await fresh.close(); }
  await registerSeller(page.request);
  await page.goto("/seller/orders");
  await expect(page.getByText("0 份订单", { exact: true })).toBeVisible();
  await page.goto(privateUrl);
  await expect(page.getByRole("heading", { name: "暂时无法打开这份订单" })).toBeVisible();
  await expect(page.getByRole("heading", { level: 1 })).toHaveCount(0);
});

test("注册密码18位完整保存，19位明确拒绝，退出后仍可用完整密码登录", async ({ page, browser, baseURL }) => {
  const email = `length-${randomUUID()}@example.invalid`;
  const password = `A1!${randomBytes(8).toString("hex").slice(0, 15)}`;
  expect(password).toHaveLength(18);
  const tooLong = password + "Z";
  let registrations = 0;
  page.on("request", request => { if (request.method() === "POST" && new URL(request.url()).pathname === "/api/v1/seller/auth/register") registrations++; });
  await page.goto("/seller/register");
  await page.getByLabel("你的称呼", { exact: true }).fill("长度验收卖家");
  await page.getByLabel("邮箱", { exact: true }).fill(email);
  await page.getByLabel("密码", { exact: true }).pressSequentially(tooLong);
  await page.getByLabel("确认密码", { exact: true }).pressSequentially(tooLong);
  await expect(page.getByLabel("密码", { exact: true })).toHaveValue(tooLong);
  await expect(page.getByLabel("确认密码", { exact: true })).toHaveValue(tooLong);
  await page.getByLabel("邮箱验证码", { exact: true }).fill("000000");
  await page.getByRole("button", { name: "验证邮箱并注册", exact: true }).click();
  await expect(page.getByText("密码最多18位，请缩短后重试。", { exact: true })).toBeVisible();
  expect(registrations).toBe(0);
  await page.getByLabel("密码", { exact: true }).fill(password);
  await page.getByLabel("确认密码", { exact: true }).fill(password);
  await page.getByRole("button", { name: "获取验证码", exact: true }).click();
  await expect(page.getByText(/验证码已发送/)).toBeVisible();
  await page.getByLabel("邮箱验证码", { exact: true }).fill(await readEmailCode(email));
  await page.getByRole("button", { name: "验证邮箱并注册", exact: true }).click();
  await expect(page).toHaveURL(/\/seller\/orders$/);
  await page.getByRole("button", { name: /退出卖家账号/ }).click();
  await expect(page).toHaveURL(/\/seller\/login$/);
  const context = await browser.newContext({ baseURL });
  try {
    const login = await context.newPage();
    await login.goto("/seller/login");
    await login.getByLabel("邮箱", { exact: true }).fill(email);
    await login.getByLabel("密码", { exact: true }).fill(password.slice(0, 12));
    await login.getByRole("button", { name: "登录卖家账号", exact: true }).click();
    await expect(login.getByText("邮箱或密码不正确。", { exact: true })).toBeVisible();
    await login.getByLabel("密码", { exact: true }).fill(password);
    await login.getByRole("button", { name: "登录卖家账号", exact: true }).click();
    await expect(login).toHaveURL(/\/seller\/orders$/);
    await expect(login.getByText(email, { exact: false })).toBeVisible();
    expect((await (await login.request.get("/api/v1/seller/auth/session")).json()).email).toBe(email);
  } finally { await context.close(); }
});
